/** Dev check: every icon is exactly 12×12 with known palette keys. */
export function iconProblems(): string[] {
  const out: string[] = [];
  for (const [name, rows] of Object.entries(ICONS)) {
    if (rows.length !== 12) out.push(`${name}: ${rows.length} rows`);
    rows.forEach((r, i) => {
      if (r.length !== 12) out.push(`${name}[${i}]: ${r.length} cols`);
      for (const ch of r) if (ch !== "." && !COLORS[ch]) out.push(`${name}[${i}]: bad key ${ch}`);
    });
  }
  return out;
}
