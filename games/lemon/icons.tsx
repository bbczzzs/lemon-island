export type IconName = keyof typeof ICONS;

const cache = new Map<IconName, ReactElement[]>();
function rectsFor(name: IconName): ReactElement[] {
  let rects = cache.get(name);
  if (rects) return rects;
  rects = [];
  ICONS[name].forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      let end = x + 1;
      while (end < row.length && row[end] === ch) end++;
      if (ch !== ".") rects!.push(<rect key={`${x}.${y}`} x={x} y={y} width={end - x} height={1} fill={COLORS[ch] ?? "#111111"} />);
      x = end;
    }
  });
  cache.set(name, rects);
  return rects;
}

/** A crisp pixel icon. Decorative: always hidden from assistive tech (pair it with text). */
export function Px({ name, size = 16, className }: { name: IconName; size?: number; className?: string }) {
  return (
    <svg className={className ? `li-px ${className}` : "li-px"} viewBox="0 0 12 12" width={size} height={size} shapeRendering="crispEdges" aria-hidden="true" focusable="false">
      {rectsFor(name)}
    </svg>
  );
}

